"""slicer.main() without PrusaSlicer: a fake slicer writes the G-code that the checks read."""

import json
import re
import zipfile

import pytest

from rh1charms import slicer
from rh1charms.export import PLAN, m600_metadata
from rh1charms.slicer import (
    AUTO_SUPPORT,
    CONFIG_ENTRY,
    M600_ENTRY,
    bridge_layers,
    main,
    plan_entry,
    stored_colour_changes,
)

PROFILE_COLOUR = "#FF8000"  # filament_colour of the Prusament PETG profile
CHANGES = [[3.0, "red"], [3.8, "green"]]
MAGNET = {"start": "white", "changes": CHANGES, "bridges": [2.4]}


def _export(folder, plan, changes=CHANGES):
    """A plate with `changes` for each name in plan, and plan.json, as export writes them."""
    folder.mkdir(parents=True, exist_ok=True)
    for name in plan:
        with zipfile.ZipFile(folder / f"{name}.3mf", "w") as z:
            z.writestr("3D/3dmodel.model", "<model/>")
            z.writestr(M600_ENTRY, m600_metadata([tuple(c) for c in changes]))
    (folder / PLAN).write_text(json.dumps(plan), encoding="utf-8")


@pytest.fixture
def fake_slicer(monkeypatch):
    """Replace PrusaSlicer. The G-code has an M600 at each height stored in the 3MF, bridge
    infill at `bridges`, support with the automatic supports if `support`, and a config
    block with the colour of --filament-colour, else the project's colour if it slices a
    project, else the profile's orange."""
    options = {"bridges": [2.4], "support": False}

    def fake(cmd, plate, gcode, profile=True, extra=()):
        with zipfile.ZipFile(plate) as z:
            names = z.namelist()
            m600 = z.read(M600_ENTRY).decode() if M600_ENTRY in names else ""
            project = z.read(CONFIG_ENTRY).decode() if CONFIG_ENTRY in names else ""
        found = re.search(r"^; filament_colour = (.*)$", project, re.MULTILINE)
        colour = PROFILE_COLOUR
        if "--filament-colour" in extra:
            colour = extra[extra.index("--filament-colour") + 1]
        elif found:
            colour = found.group(1)
        moves = "".join(f";Z:{z}\nM600\n" for z in re.findall(r'print_z="([\d.]+)"', m600))
        moves += "".join(f";Z:{z}\n;TYPE:Bridge infill\nG1 X1 E1\n" for z in options["bridges"])
        if options["support"] and "--support-material-auto" in extra:
            moves += ";Z:0.4\n;TYPE:Support material\nG1 X1 E1\n"
        gcode.write_text(
            "; generated by PrusaSlicer 2.9.6\n" + moves
            + "; estimated printing time (normal mode) = 13m 47s\n; filament used [g] = 4.27\n"
            + f"; prusaslicer_config = begin\n; binary_gcode = 0\n; filament_colour = {colour}\n"
            + f"; printer_settings_id = {slicer.PRINTER}\n; prusaslicer_config = end\n",
            encoding="utf-8")

    monkeypatch.setattr(slicer, "slice_plate", fake)
    monkeypatch.setattr(slicer, "prusaslicer_command", lambda: ["prusa-slicer"])
    return options


def _result(capsys, name="tag"):
    """The line that main() printed for the plate."""
    return next(line for line in capsys.readouterr().out.splitlines()
                if line.startswith(name + " "))


def test_plate_as_designed_is_ok(tmp_path, fake_slicer, capsys):
    _export(tmp_path, {"tag": MAGNET})
    assert main(tmp_path) == 0
    assert _result(capsys).endswith("OK")
    with zipfile.ZipFile(tmp_path / "projects" / "tag.3mf") as z:
        config = z.read(CONFIG_ENTRY).decode()
    assert "; filament_colour = #ECE8DC" in config  # white, not the profile's orange


def test_ceiling_that_does_not_print_as_a_bridge_is_reported(tmp_path, fake_slicer, capsys):
    """The support probe leaves bridges out: only this check fails if a ceiling the design
    lists (a pocket roof, the clip channel) does not print as a bridge."""
    fake_slicer["bridges"] = [3.0]
    _export(tmp_path, {"tag": MAGNET})
    assert main(tmp_path) == 1
    assert "no bridge infill at Z [2.4] (bridges at [3.0])" in _result(capsys)


def test_support_is_reported(tmp_path, fake_slicer, capsys):
    fake_slicer["support"] = True
    _export(tmp_path, {"tag": MAGNET})
    assert main(tmp_path) == 1
    assert "needs support (1 extrusions)" in _result(capsys)


def test_missing_colour_change_is_reported(tmp_path, fake_slicer, capsys):
    _export(tmp_path, {"tag": MAGNET}, changes=CHANGES[:1])
    assert main(tmp_path) == 1
    assert "expected M600 at [3.0, 3.8], found 1 at [3.0]" in _result(capsys)


@pytest.mark.parametrize("plan, message", [
    ({}, "not in plan.json: export it again"),
    ({"tag": {"start": "white", "changes": CHANGES}}, "incomplete entry in plan.json"),
    ({"tag": {"start": "pink", "changes": CHANGES, "bridges": []}},
     "unknown filament pink in plan.json"),
])
def test_plate_the_plan_cannot_describe_gives_one_clear_problem(tmp_path, fake_slicer,
                                                                capsys, plan, message):
    _export(tmp_path, {"tag": MAGNET})
    (tmp_path / PLAN).write_text(json.dumps(plan or {"other": MAGNET}), encoding="utf-8")
    assert main(tmp_path) == 1
    line = _result(capsys)
    assert message in line and "M600 at [" not in line and "3MF stores" not in line


def test_support_probe_turns_off_the_first_layer_expansion():
    """The profile widens the first layer of every support by 3 mm: a column trimmed to
    nothing under the clip channel's free edge left a pad on the bed (README)."""
    assert AUTO_SUPPORT[:3] == ["--support-material", "--support-material-auto",
                                "--dont-support-bridges"]
    assert AUTO_SUPPORT[3:] == ["--raft-first-layer-expansion", "0"]


def test_bridge_layers():
    text = ";Z:2.2\n;TYPE:Perimeter\n;Z:2.4\n;TYPE:Bridge infill\n;TYPE:Bridge infill\n;Z:3\n"
    assert bridge_layers(text) == [2.4]


def test_plan_entry():
    assert plan_entry({"p": MAGNET}, "p") == ("#ECE8DC", [(3.0, "#C62127"), (3.8, "#3E9B35")],
                                              [2.4], [])


def test_stored_colour_changes(tmp_path):
    _export(tmp_path, {"p": MAGNET})
    assert stored_colour_changes(tmp_path / "p.3mf") == [(3.0, "#C62127"), (3.8, "#3E9B35")]
